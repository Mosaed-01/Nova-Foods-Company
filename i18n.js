const i18n = {
  current: localStorage.getItem('novaLang') || 'en',

  init() {
    this.apply(this.current);
    const switchBtn = document.getElementById('langSwitch');
    if (switchBtn) {
      switchBtn.addEventListener('click', () => this.toggle());
    }
  },

  toggle() {
    const newLang = this.current === 'en' ? 'ar' : 'en';
    this.apply(newLang);
  },

  apply(lang) {
    this.current = lang;
    localStorage.setItem('novaLang', lang);

    const html = document.documentElement;
    html.setAttribute('lang', lang);
    html.setAttribute('dir', lang === 'ar' ? 'rtl' : 'ltr');
    document.body.classList.toggle('rtl', lang === 'ar');

    const dict = translations[lang];

    // Plain text
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      if (dict[key]) {
        el.textContent = dict[key];
      }
    });

    // HTML content
    document.querySelectorAll('[data-i18n-html]').forEach(el => {
      const key = el.getAttribute('data-i18n-html');
      if (dict[key]) {
        el.innerHTML = dict[key];
      }
    });

    // Update language switcher label
    const label = document.getElementById('langLabel');
    if (label) label.textContent = dict['lang.switchTo'];

    // Update year in footer (it's part of the translation string)
    const yearEl = document.getElementById('year');
    if (yearEl) yearEl.textContent = new Date().getFullYear();

    // Update page title
    if (lang === 'ar') {
      document.title = 'نوفا فودز — تجارة وتوزيع المواد الغذائية دولياً';
    } else {
      document.title = 'Nova Foods — International Food Trading & Distribution';
    }
  }
};

// Initialize i18n once DOM is ready
if (document.readyState === 'loading') {
  document.addEventListener('DOMContentLoaded', () => i18n.init());
} else {
  i18n.init();
}
